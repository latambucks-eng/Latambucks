// elige por `lang`; si falta un idioma, cae a español.

export function fill(text, vars) {
  if (!text || !vars) return text || "";
  return Object.entries(vars).reduce(
    (acc, [key, value]) => acc.split(`{${key}}`).join(String(value)),
    text
  );
}

