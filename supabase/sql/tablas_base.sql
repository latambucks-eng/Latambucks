-- ============================================================
-- 8. STORAGE — Bucket público "capturas-tareas"
-- ============================================================
-- Los anunciantes y admins necesitan ver las capturas para revisarlas,
-- por eso el bucket es público (misma lógica que comprobantes-pagos).
INSERT INTO storage.buckets (id, name, public)
VALUES ('capturas-tareas', 'capturas-tareas', true)
ON CONFLICT (id) DO NOTHING;

ALTER TABLE storage.objects ENABLE ROW LEVEL SECURITY;

-- Cada usuario autenticado sube sólo a su propia carpeta (<uid>/archivo).
-- Idéntica a la definida en rls_policies.sql (DROP + CREATE la mantiene única).
DROP POLICY IF EXISTS "capturas_upload_own" ON storage.objects;
CREATE POLICY "capturas_upload_own" ON storage.objects
  FOR INSERT TO authenticated
  WITH CHECK (
    bucket_id = 'capturas-tareas'
    AND split_part(name, '/', 1) = auth.uid()::text
  );

-- ============================================================
-- 9. VERIFICACIÓN
-- ============================================================
-- Debe devolver 5 tablas y 1 bucket.
SELECT 'tabla' AS tipo, tablename AS nombre
FROM pg_tables
WHERE schemaname = 'public'
  AND tablename IN (
    'perfiles', 'campanas_locales', 'historial_tareas',
    'retiros', 'pruebas_tareas_locales'
  )
UNION ALL
SELECT 'bucket', id FROM storage.buckets WHERE id = 'capturas-tareas'
ORDER BY tipo, nombre;