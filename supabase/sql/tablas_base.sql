-- ============================================================
-- 1. PERFILES
-- ============================================================
CREATE TABLE IF NOT EXISTS public.perfiles (
  id                        uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  email                     text NOT NULL,
  pais                      text NOT NULL,
  alias_mp                  text,
  wallet_btc                text,
  saldo_disponible          numeric NOT NULL DEFAULT 0,
  saldo_pendiente           numeric NOT NULL DEFAULT 0,
  referido_por              uuid REFERENCES public.perfiles(id) ON DELETE SET NULL,
  codigo_referido           text NOT NULL UNIQUE,
  puntos_por_referidos      numeric NOT NULL DEFAULT 0,
  ultima_ip                 text,
  dispositivo_info          text,
  cuenta_bloqueada          boolean NOT NULL DEFAULT false,
  motivo_bloqueo            text,
  creado_el                 timestamptz NOT NULL DEFAULT now(),
  retener_pagos             boolean NOT NULL DEFAULT false,
  destino_pago              text,
  titular_pago              text,
  ultimo_ciclo_procesado    text,
  role                      text NOT NULL DEFAULT 'user',
  saldo_promocion           numeric NOT NULL DEFAULT 0,
  metodo_pago_preferido     text,
  saldo_bono                numeric NOT NULL DEFAULT 0,
  giros_gratuitos_restantes integer NOT NULL DEFAULT 3,
  giros_extra_disponibles   integer NOT NULL DEFAULT 0,
  ultimo_reinicio_giros     timestamptz NOT NULL DEFAULT now(),
  pais_detectado            text
);

COMMENT ON COLUMN public.perfiles.saldo_bono IS
  'Tracker de cuánto del bono de bienvenida queda en saldo_disponible sin consumir. Se consume primero al crear campañas (sin 30% de comisión). Se reinicia a 0 al retirar.';

CREATE INDEX IF NOT EXISTS perfiles_codigo_referido_idx ON public.perfiles (codigo_referido);
CREATE INDEX IF NOT EXISTS perfiles_referido_por_idx ON public.perfiles (referido_por);
CREATE INDEX IF NOT EXISTS perfiles_role_idx ON public.perfiles (role);

-- ============================================================
-- 2. CAMPAÑAS LOCALES (tareas de anunciantes)
-- ============================================================
CREATE TABLE IF NOT EXISTS public.campanas_locales (
  id                    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  titulo                text NOT NULL,
  enlace_url            text NOT NULL,
  puntos_recompensa     numeric NOT NULL,
  visitas_compradas     integer NOT NULL,
  visitas_actuales      integer NOT NULL DEFAULT 0,
  activa                boolean NOT NULL DEFAULT true,
  creado_el             timestamptz NOT NULL DEFAULT now(),
  anunciante_email      text,
  monto_invertido_ars   numeric NOT NULL DEFAULT 0,
  estado_pago           text NOT NULL DEFAULT 'pendiente',
  created_at            timestamptz NOT NULL DEFAULT now(),
  moneda                text NOT NULL DEFAULT 'ARS',
  ganancia_plataforma   numeric NOT NULL DEFAULT 0,
  instrucciones         text,
  reintegrado           boolean NOT NULL DEFAULT false,
  comprobante_pago_url  text,
  pago_con_saldo        boolean NOT NULL DEFAULT false,
  paypal_surcharge      numeric NOT NULL DEFAULT 0
);

COMMENT ON COLUMN public.campanas_locales.moneda IS
  'Distingue la moneda de pago de la campaña: ARS para Argentina, USD para Latam/Payoneer';
COMMENT ON COLUMN public.campanas_locales.comprobante_pago_url IS
  'URL pública del comprobante de pago subido por el anunciante';
COMMENT ON COLUMN public.campanas_locales.paypal_surcharge IS
  'Recargo de PayPal cobrado al anunciante (tarifa de procesamiento). No se reembolsa al reintegrar saldo.';

CREATE INDEX IF NOT EXISTS campanas_locales_activa_idx ON public.campanas_locales (activa);
CREATE INDEX IF NOT EXISTS campanas_locales_estado_pago_idx ON public.campanas_locales (estado_pago);
CREATE INDEX IF NOT EXISTS campanas_locales_anunciante_idx ON public.campanas_locales (anunciante_email);
CREATE INDEX IF NOT EXISTS campanas_locales_created_at_idx ON public.campanas_locales (created_at DESC);

-- ============================================================
-- 3. HISTORIAL DE TAREAS (ganancias del usuario)
-- ============================================================
CREATE TABLE IF NOT EXISTS public.historial_tareas (
  id                        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id                uuid NOT NULL REFERENCES public.perfiles(id) ON DELETE CASCADE,
  proveedor                 text NOT NULL,
  tarea_externa_id          text NOT NULL,
  nombre_tarea              text,
  puntos_ganados            numeric NOT NULL DEFAULT 0,
  puntos_comision_referido  numeric NOT NULL DEFAULT 0,
  estado                    text NOT NULL DEFAULT 'aprobado',
  liberacion_fecha          timestamptz NOT NULL DEFAULT now(),
  creado_el                 timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS historial_tareas_usuario_idx ON public.historial_tareas (usuario_id);
CREATE INDEX IF NOT EXISTS historial_tareas_proveedor_idx ON public.historial_tareas (proveedor, tarea_externa_id);
CREATE INDEX IF NOT EXISTS historial_tareas_creado_el_idx ON public.historial_tareas (creado_el DESC);

-- ============================================================
-- 4. RETIROS
-- ============================================================
CREATE TABLE IF NOT EXISTS public.retiros (
  id                        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id                   uuid NOT NULL REFERENCES public.perfiles(id) ON DELETE CASCADE,
  metodo_pago               text NOT NULL,
  detalles_pago             text NOT NULL,
  titular_nombre            text,
  puntos_solicitados        numeric NOT NULL,
  estado                    text NOT NULL DEFAULT 'pendiente',
  comentario_administrador  text,
  creado_el                 timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS retiros_user_id_idx ON public.retiros (user_id);
CREATE INDEX IF NOT EXISTS retiros_estado_idx ON public.retiros (estado);
CREATE INDEX IF NOT EXISTS retiros_creado_el_idx ON public.retiros (creado_el DESC);

-- ============================================================
-- 5. PRUEBAS DE TAREAS LOCALES (capturas subidas por el usuario)
-- ============================================================
CREATE TABLE IF NOT EXISTS public.pruebas_tareas_locales (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campana_id      integer NOT NULL REFERENCES public.campanas_locales(id) ON DELETE CASCADE,
  usuario_id      uuid NOT NULL REFERENCES public.perfiles(id) ON DELETE CASCADE,
  texto_prueba    text NOT NULL,
  url_captura     text NOT NULL,
  estado          text NOT NULL DEFAULT 'pendiente',
  creado_el       timestamptz NOT NULL DEFAULT now(),
  disputa_motivo  text,
  rechazo_motivo  text
);

CREATE INDEX IF NOT EXISTS pruebas_campana_idx ON public.pruebas_tareas_locales (campana_id);
CREATE INDEX IF NOT EXISTS pruebas_usuario_idx ON public.pruebas_tareas_locales (usuario_id);
CREATE INDEX IF NOT EXISTS pruebas_estado_idx ON public.pruebas_tareas_locales (estado);

