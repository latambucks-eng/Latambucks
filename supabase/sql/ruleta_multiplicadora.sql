-- ============================================================
-- 3. CADA ENCUESTA APROBADA SUMA AL SALDO APOSTABLE
-- ============================================================
CREATE OR REPLACE FUNCTION public.fn_sumar_saldo_encuestas()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_prov text := lower(coalesce(NEW.proveedor, ''));
  v_es_encuesta boolean;
BEGIN
  v_es_encuesta := v_prov IN ('cpx_research', 'cpx', 'theoremreach', 'timewall',
                              'rapidoreach', 'cpagrip', 'pollfish', 'encuestas', 'encuesta');

  -- 1) ENCUESTA APROBADA: suma al saldo apostable, una sola vez por tarea.
  IF NEW.estado = 'aprobado' THEN
    IF TG_OP = 'UPDATE' AND coalesce(OLD.estado, '') = 'aprobado' THEN
      RETURN NEW; -- ya estaba aprobada: no se suma dos veces
    END IF;

    IF v_es_encuesta AND coalesce(NEW.puntos_ganados, 0) > 0 THEN
      UPDATE public.perfiles
         SET saldo_encuestas = coalesce(saldo_encuestas, 0) + NEW.puntos_ganados
       WHERE id = NEW.usuario_id;
    END IF;
    RETURN NEW;
  END IF;

  -- 2) REVERSO: la encuesta se anula y el usuario ya no tiene esos puntos.
  --    El saldo apostable se descuenta igual (sin quedar negativo), para que
  --    nunca se pueda apostar plata que el sistema ya devolvió/descontó.
  IF NEW.estado = 'reversado'
     AND TG_OP = 'UPDATE'
     AND coalesce(OLD.estado, '') = 'aprobado'
     AND v_es_encuesta THEN
    UPDATE public.perfiles
       SET saldo_encuestas = greatest(0, coalesce(saldo_encuestas, 0)
                                        - coalesce(NEW.puntos_ganados, 0))
     WHERE id = NEW.usuario_id;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_historial_saldo_encuestas ON public.historial_tareas;
CREATE TRIGGER trg_historial_saldo_encuestas
AFTER INSERT OR UPDATE ON public.historial_tareas
FOR EACH ROW EXECUTE FUNCTION public.fn_sumar_saldo_encuestas();

-- ============================================================
-- 4. UN RETIRO DESCUENTA DEL SALDO APOSTABLE
-- ============================================================
CREATE OR REPLACE FUNCTION public.fn_descontar_saldo_encuestas_retiro()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_puntos numeric := coalesce(NEW.puntos_solicitados, 0);
BEGIN
  -- Retiro creado: esos puntos dejan de estar disponibles para apostar.
  IF TG_OP = 'INSERT' THEN
    UPDATE public.perfiles
       SET saldo_encuestas = greatest(0, coalesce(saldo_encuestas, 0) - v_puntos)
     WHERE id = NEW.user_id;
    RETURN NEW;
  END IF;

  -- Retiro rechazado: la plata vuelve al usuario, y vuelve a ser apostable.
  IF NEW.estado = 'rechazado' AND coalesce(OLD.estado, '') <> 'rechazado' THEN
    UPDATE public.perfiles
       SET saldo_encuestas = coalesce(saldo_encuestas, 0) + v_puntos
     WHERE id = NEW.user_id;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_retiro_saldo_encuestas ON public.retiros;
CREATE TRIGGER trg_retiro_saldo_encuestas
AFTER INSERT OR UPDATE ON public.retiros
FOR EACH ROW EXECUTE FUNCTION public.fn_descontar_saldo_encuestas_retiro();

-- ============================================================
-- 5. LÍMITES POR PAÍS
-- ============================================================
CREATE OR REPLACE FUNCTION public.fn_wheel_limits(p_pais text)
RETURNS jsonb
LANGUAGE sql
IMMUTABLE
AS $$
  SELECT CASE
    -- Se acepta el código ISO (el que fija la detección por IP) y también el
    -- nombre completo, por si algún perfil viejo lo guardó así.
    WHEN upper(coalesce(p_pais, '')) IN ('US', 'USA', 'ESTADOS UNIDOS', 'UNITED STATES')
      THEN '{"requisito": 500, "apuesta_max": 1000, "tope_neto": 2000}'::jsonb
    ELSE '{"requisito": 50, "apuesta_max": 200, "tope_neto": 400}'::jsonb
  END;
$$;

-- ============================================================
-- 6. PUNTOS GANADOS HOY EN ENCUESTAS (día UTC)
-- ============================================================
CREATE OR REPLACE FUNCTION public.fn_encuestas_ganadas_hoy(p_user_id uuid)
RETURNS numeric
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT coalesce(sum(h.puntos_ganados), 0)
    FROM public.historial_tareas h
   WHERE h.usuario_id = p_user_id
     AND h.estado = 'aprobado'
     AND lower(coalesce(h.proveedor, '')) IN ('cpx_research', 'cpx', 'theoremreach', 'timewall',
                                              'rapidoreach', 'cpagrip', 'pollfish', 'encuestas', 'encuesta')
     AND h.creado_el >= (date_trunc('day', now() AT TIME ZONE 'utc') AT TIME ZONE 'utc');
$$;

-- ============================================================
-- 7. ESTADO DE LA RULETA (lo que ve el frontend)
-- ============================================================
CREATE OR REPLACE FUNCTION public.fn_wheel_snapshot(
  p_pais text, p_req numeric, p_apuesta_max numeric, p_tope numeric,
  p_ganado numeric, p_giros integer, p_neto numeric,
  p_saldo_enc numeric, p_saldo_disp numeric, p_motivo text
)
RETURNS jsonb
LANGUAGE sql
IMMUTABLE
AS $$
  SELECT jsonb_build_object(
    'pais', p_pais,
    'requisito', p_req,
    'ganado_hoy', p_ganado,
    'giros_usados', p_giros,
    'giros_restantes', greatest(0, 4 - p_giros),
    'apuesta_max', p_apuesta_max,
    'tope_neto', p_tope,
    'neto_hoy', p_neto,
    'saldo_encuestas', p_saldo_enc,
    'saldo_disponible', p_saldo_disp,
    'habilitado', p_motivo IS NULL,
    'motivo', p_motivo
  );
$$;

CREATE OR REPLACE FUNCTION public.wheel_status()
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_uid uuid := auth.uid();
  v_pais text;
  v_lim jsonb;
  v_req numeric; v_max numeric; v_tope numeric;
  v_ganado numeric := 0;
  v_giros integer := 0;
  v_neto numeric := 0;
  v_saldo_enc numeric := 0;
  v_saldo_disp numeric := 0;
  v_motivo text := NULL;
BEGIN
  IF v_uid IS NULL THEN
    RAISE EXCEPTION 'No autenticado';
  END IF;

  SELECT upper(coalesce(p.pais_detectado, p.pais, '')),
         coalesce(p.saldo_encuestas, 0),
         coalesce(p.saldo_disponible, 0)
    INTO v_pais, v_saldo_enc, v_saldo_disp
    FROM public.perfiles p
   WHERE p.id = v_uid;

  IF v_pais IS NULL THEN
    RAISE EXCEPTION 'Perfil no encontrado';
  END IF;

  v_lim := public.fn_wheel_limits(v_pais);
  v_req := (v_lim->>'requisito')::numeric;
  v_max := (v_lim->>'apuesta_max')::numeric;
  v_tope := (v_lim->>'tope_neto')::numeric;

  v_ganado := public.fn_encuestas_ganadas_hoy(v_uid);

  SELECT count(*), coalesce(sum(w.ganancia_neta), 0)
    INTO v_giros, v_neto
    FROM public.wheel_spins w
   WHERE w.usuario_id = v_uid
     AND w.creado_el >= (date_trunc('day', now() AT TIME ZONE 'utc') AT TIME ZONE 'utc');

  IF v_giros >= 4 THEN
    v_motivo := 'sin_giros';
  ELSIF v_ganado < v_req THEN
    v_motivo := 'requisito';
  ELSIF v_neto >= v_tope THEN
    v_motivo := 'tope';
  ELSIF v_saldo_enc < 1 THEN
    v_motivo := 'saldo_encuestas';
  END IF;

  RETURN public.fn_wheel_snapshot(v_pais, v_req, v_max, v_tope, v_ganado,
                                  v_giros, v_neto, v_saldo_enc, v_saldo_disp, v_motivo);
END;
$$;

-- ============================================================
-- 8. GIRAR (validación + matemática + saldo, todo atómico)
-- ============================================================
CREATE OR REPLACE FUNCTION public.spin_multiplier_wheel(p_apuesta numeric)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_uid uuid := auth.uid();
  v_pais text;
  v_lim jsonb;
  v_req numeric; v_max numeric; v_tope numeric;
  v_apuesta numeric := round(coalesce(p_apuesta, 0), 2);
  v_ganado numeric := 0;
  v_giros integer := 0;
  v_neto numeric := 0;
  v_saldo_enc numeric := 0;
  v_saldo_disp numeric := 0;
  v_motivo text := NULL;
  v_roll numeric;
  v_mult numeric;
  v_premio numeric;
  v_neto_giro numeric;
  v_resultado text;
BEGIN
  IF v_uid IS NULL THEN
    RAISE EXCEPTION 'No autenticado';
  END IF;

  -- Bloquea el perfil: dos giros simultáneos no pueden pisarse el saldo.
  SELECT upper(coalesce(pais_detectado, pais, '')),
         coalesce(saldo_encuestas, 0),
         coalesce(saldo_disponible, 0)
    INTO v_pais, v_saldo_enc, v_saldo_disp
    FROM public.perfiles
   WHERE id = v_uid
   FOR UPDATE;

  IF v_pais IS NULL THEN
    RAISE EXCEPTION 'Perfil no encontrado';
  END IF;

  v_lim := public.fn_wheel_limits(v_pais);
  v_req := (v_lim->>'requisito')::numeric;
  v_max := (v_lim->>'apuesta_max')::numeric;
  v_tope := (v_lim->>'tope_neto')::numeric;

  v_ganado := public.fn_encuestas_ganadas_hoy(v_uid);

  SELECT count(*), coalesce(sum(w.ganancia_neta), 0)
    INTO v_giros, v_neto
    FROM public.wheel_spins w
   WHERE w.usuario_id = v_uid
     AND w.creado_el >= (date_trunc('day', now() AT TIME ZONE 'utc') AT TIME ZONE 'utc');

  IF v_giros >= 4 THEN
    v_motivo := 'sin_giros';
  ELSIF v_ganado < v_req THEN
    v_motivo := 'requisito';
  ELSIF v_neto >= v_tope THEN
    v_motivo := 'tope';
  ELSIF v_apuesta <= 0 THEN
    v_motivo := 'apuesta_invalida';
  ELSIF v_apuesta > v_max THEN
    v_motivo := 'apuesta_max';
  ELSIF v_apuesta > v_saldo_enc THEN
    v_motivo := 'saldo_encuestas';
  ELSIF v_apuesta > v_saldo_disp THEN
    -- Nunca apostar más de lo que el usuario tiene realmente disponible:
    -- un reverso puede dejar el saldo disponible en cero con deuda.
    v_motivo := 'saldo_encuestas';
  END IF;

  IF v_motivo IS NOT NULL THEN
    RETURN public.fn_wheel_snapshot(v_pais, v_req, v_max, v_tope, v_ganado,
                                    v_giros, v_neto, v_saldo_enc, v_saldo_disp, v_motivo)
           || jsonb_build_object('ok', false, 'apuesta', v_apuesta);
  END IF;

  -- Probabilidades: 45% x1.1 · 30% x1.0 · 20% x0.5 · 5% x1.5
  v_roll := random();
  v_mult := CASE
    WHEN v_roll < 0.45 THEN 1.1
    WHEN v_roll < 0.75 THEN 1.0
    WHEN v_roll < 0.95 THEN 0.5
    ELSE 1.5
  END;

  v_premio := round(v_apuesta * v_mult, 2);
  v_neto_giro := round(v_premio - v_apuesta, 2);

  -- Tope de ganancia neta diaria: recorta el premio si se excede.
  IF v_neto_giro > 0 AND v_neto + v_neto_giro > v_tope THEN
    v_neto_giro := round(v_tope - v_neto, 2);
    v_premio := round(v_apuesta + v_neto_giro, 2);
  END IF;

  v_resultado := CASE
    WHEN v_mult = 1.5 THEN 'jackpot'
    WHEN v_mult = 1.1 THEN 'win'
    WHEN v_mult = 1.0 THEN 'recover'
    ELSE 'half'
  END;

  UPDATE public.perfiles
     SET saldo_disponible = coalesce(saldo_disponible, 0) + v_neto_giro,
         saldo_encuestas  = greatest(0, coalesce(saldo_encuestas, 0) + v_neto_giro)
   WHERE id = v_uid;

  INSERT INTO public.wheel_spins (usuario_id, pais, apuesta, multiplicador, premio, ganancia_neta, resultado)
  VALUES (v_uid, v_pais, v_apuesta, v_mult, v_premio, v_neto_giro, v_resultado);

  RETURN public.fn_wheel_snapshot(v_pais, v_req, v_max, v_tope, v_ganado,
                                  v_giros, v_neto, v_saldo_enc, v_saldo_disp, NULL)
         || jsonb_build_object(
              'ok', true,
              'apuesta', v_apuesta,
              'multiplicador', v_mult,
              'premio', v_premio,
              'ganancia_neta', v_neto_giro,
              'resultado', v_resultado,
              'giros_usados', v_giros + 1,
              'giros_restantes', greatest(0, 3 - v_giros),
              'neto_hoy', round(v_neto + v_neto_giro, 2),
              'saldo_encuestas', greatest(0, v_saldo_enc + v_neto_giro),
              'saldo_disponible', round(v_saldo_disp + v_neto_giro, 2)
            );
END;
$$;

