-- ============================================================
-- 1.b PROTECCIÓN DEL SALDO APOSTABLE (anti-manipulación)
-- ============================================================
-- El usuario puede editar su perfil (nombre, avatar, país) pero NO su
-- saldo. Sin esto, cualquiera podía hacer un PATCH a /perfiles con
-- saldo_encuestas = 999999 y apostar puntos que nunca ganó.
-- Solo bloquea el UPDATE directo con rol 'authenticated': las funciones
-- SECURITY DEFINER (postbacks, ruleta, retiros, bono) corren como owner y
-- siguen funcionando igual.
CREATE OR REPLACE FUNCTION public.fn_proteger_saldos_ruleta()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF current_user <> 'authenticated' THEN
    RETURN NEW;
  END IF;

  IF NEW.saldo_encuestas IS DISTINCT FROM OLD.saldo_encuestas
     OR NEW.saldo_bono IS DISTINCT FROM OLD.saldo_bono
     OR NEW.pais_detectado IS DISTINCT FROM OLD.pais_detectado THEN
    RAISE EXCEPTION 'Operación no permitida sobre el saldo';
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_proteger_saldos_ruleta ON public.perfiles;
CREATE TRIGGER trg_proteger_saldos_ruleta
  BEFORE UPDATE ON public.perfiles
  FOR EACH ROW EXECUTE FUNCTION public.fn_proteger_saldos_ruleta();

